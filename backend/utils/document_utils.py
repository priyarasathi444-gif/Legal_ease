import html
import re
from io import BytesIO
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt
from fpdf import FPDF

ASSETS_DIR = Path(__file__).resolve().parents[2] / "assets"
LOGO_PATH = ASSETS_DIR / "logo.png"


def sanitize_text(text: str) -> str:
    """Remove problematic typographic characters for clean export."""
    replacements = {
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2013": "-",
        "\u2014": "-",
        "\u00a0": " ",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return re.sub(r"[^\S\r\n]+", " ", text).strip()


def _split_terms(terms_text: str):
    return [t.strip() for t in terms_text.split(";") if t.strip()]


def format_docx(text: str, doc_type: str, terms_text: str = "") -> bytes:
    doc = Document()
    section = doc.sections[0]

    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)
    section.left_margin = Inches(0.8)
    section.right_margin = Inches(0.8)

    if LOGO_PATH.exists():
        paragraph = doc.add_paragraph()
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
        paragraph.add_run().add_picture(str(LOGO_PATH), width=Inches(1.8))

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run(doc_type.upper())
    run.bold = True
    run.font.name = "Times New Roman"
    run.font.size = Pt(16)

    for raw_line in sanitize_text(text).splitlines():
        line = raw_line.strip()
        if not line:
            continue

        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(6)
        r = p.add_run(line)
        r.font.name = "Times New Roman"
        r.font.size = Pt(11)

    terms = _split_terms(terms_text)
    if terms:
        doc.add_paragraph()
        heading = doc.add_paragraph()
        r = heading.add_run("Key Terms")
        r.bold = True
        r.font.name = "Times New Roman"
        r.font.size = Pt(12)

        table = doc.add_table(rows=1, cols=2)
        table.style = "Table Grid"
        table.rows[0].cells[0].text = "No."
        table.rows[0].cells[1].text = "Term / Condition"

        for index, term in enumerate(terms, 1):
            cells = table.add_row().cells
            cells[0].text = str(index)
            cells[1].text = term

    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.add_run("Generated by LegalEase | Review before legal use")

    buffer = BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


class LegalPDF(FPDF):
    def __init__(self, doc_type):
        super().__init__()
        self.doc_type = doc_type

    def header(self):
        if LOGO_PATH.exists():
            try:
                self.image(str(LOGO_PATH), x=85, y=8, w=40)
                self.ln(25)
            except Exception:
                self.ln(8)
        else:
            self.ln(8)

        self.set_font("Arial", "B", 14)
        self.cell(0, 10, self.doc_type.upper(), align="C")
        self.ln(12)

    def footer(self):
        self.set_y(-15)
        self.set_font("Arial", "I", 8)
        self.cell(
            0, 10,
            "Generated by LegalEase | Review before legal use",
            align="C",
        )


def format_pdf(text: str, doc_type: str) -> bytes:
    pdf = LegalPDF(doc_type)
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    pdf.set_font("Arial", size=11)

    for raw_line in sanitize_text(text).splitlines():
        line = raw_line.strip()
        if not line:
            pdf.ln(4)
            continue

        # Basic section heading detection.
        if (
            len(line) < 80
            and (line.isupper() or re.match(r"^\d+[\.\)]\s", line))
        ):
            pdf.set_font("Arial", "B", 11)
        else:
            pdf.set_font("Arial", size=11)

        safe_line = line.encode("latin-1", "replace").decode("latin-1")
        pdf.multi_cell(0, 7, safe_line)
        pdf.ln(1)

    return bytes(pdf.output())


def format_html_preview(text: str) -> str:
    escaped = html.escape(text)
    escaped = escaped.replace("\n", "<br>")
    return f"""
    <div style="
        background:#151515;
        color:#f3f3f3;
        padding:24px;
        border-radius:12px;
        max-height:650px;
        overflow-y:auto;
        font-family:Georgia, 'Times New Roman', serif;
        line-height:1.7;
        border:1px solid #333;
    ">
        {escaped}
    </div>
    """
